export function buildSpecialist(spec, d) {
  const routing = effectiveRouting(null);
  const model = routing.tiers[spec.tier]?.model ?? "inherit";
  const tools = spec.access === "write" ? "tools: Read, Grep, Glob, Edit, Write, Bash" : "tools: Read, Grep, Glob, Bash";
  const t = readFileSync(pluginFile("templates", "specialist-agent.md"), "utf8").replace(/\r\n?/g, "\n");
  return t
    .replace(/\{\{name\}\}/g, spec.name)
    .replace(/\{\{description\}\}/g, JSON.stringify(`Project specialist for ${spec.focus}. Use for tasks in this domain.`))
    .replace(/\{\{tools_line\}\}/g, tools)
    .replace(/\{\{model\}\}/g, model)
    .replace(/\{\{title\}\}/g, spec.name.replace(/-/g, " "))
    .replace(/\{\{project\}\}/g, d.root_name)
    .replace(/\{\{focus\}\}/g, spec.focus);
}

function gapTask(gap, d, id) {
  const testCmd = d.commands.test?.cmd;
  const cmd = gap.validation_key ? (d.commands[gap.validation_key]?.cmd ?? null) : gap.validation_cmd;
  const data = {
    id,
    title: gap.title,
    status: "draft",
    agent: gap.agent,
    skills: [],
    model_tier: loadRegistry().agents[gap.agent]?.tier ?? "coding",
    priority: gap.priority ?? "p2",
    origin: `bootstrap:${gap.id}`,
    depends_on: [],
    files_allowed: gap.scope,
    files_excluded: [],
    review: gap.review ? ["code", ...gap.review.filter((r) => r !== "code")] : ["code"],
    validation: [{ cmd: cmd ?? (testCmd ?? "<fill in the command that proves this task>"), expect: "exit 0" }],
    acceptance: gap.acceptance,
    max_retries: 2,
    attempts: 0,
    created: today(),
    updated: today(),
  };
  const body = `
## Objective

${gap.title}.

## Context

Generated by bootstrap rule \`${gap.id}\` from discovery of this repository
(see \`project-context/project-profile.md\`). Review and adjust scope and
validation before promoting this task to \`ready\`.

## Steps

1. Read the relevant profile sections and existing files in scope.
2. Implement the smallest change that satisfies the acceptance criteria.
3. Run every validation command and record results in the handoff.

## Blockers

Stop with a \`blocked\` handoff if the work needs files outside
\`files_allowed\`, credentials, or a product decision.

## Deliverables

- Changes inside \`files_allowed\`
- \`reports/handoffs/${id}.md\`
`;
  return `---\n${stringifyYaml(data)}\n---\n${body}`;
}

// ----------------------------------------------------- desired state + diff
function readManifest(root) {
  const p = join(root, MANIFEST_REL);
  if (!existsSync(p)) return { version: 1, files: {} };
  try { return readJson(p); } catch { return { version: 1, files: {}, corrupt: true }; }
}

function extractSection(text, [start, end]) {
  const s = text.indexOf(start);
  const e = text.indexOf(end);
  if (s === -1 || e === -1 || e < s) return null;
  return text.slice(s + start.length, e).replace(/^\n/, "").replace(/\n$/, "");
}

function replaceSection(text, [start, end], content) {
  const s = text.indexOf(start);
  const e = text.indexOf(end);
  return text.slice(0, s) + `${start}\n${content}\n` + text.slice(e);
}

/**
 * Compute the plan: discovery, capability mapping, and per-file actions.
 * Pure: never writes.
 */
export function plan(root, { discovery } = {}) {
  const d = discovery ?? discover(root);
  const inv = inventory(root);
  const caps = mapCapabilities(d, inv);
  const manifest = readManifest(root);
  const actions = [];
  const read = (rel) => (existsSync(join(root, rel)) ? readFileSync(join(root, rel), "utf8").replace(/\r\n?/g, "\n") : null);

  const fileAction = (rel, content, kind, reason) => {
    const current = read(rel);
    const want = sha(content);
    const entry = manifest.files[rel];
    if (current === null) return actions.push({ action: "create", path: rel, kind, reason, content, hash: want });
    const cur = sha(current);
    if (cur === want) return actions.push({ action: "unchanged", path: rel, kind, reason, hash: want });
    if (entry && entry.hash === cur) return actions.push({ action: "update", path: rel, kind, reason, content, hash: want });
    return actions.push({ action: "conflict", path: rel, kind, reason: entry ? "modified since bootstrap wrote it (user customization)" : "file exists and was not created by bootstrap", content, hash: want });
  };

  const sectionAction = (rel, markers, content, kind, reason, { createIfMissing }) => {
    const current = read(rel);
    const want = sha(content);
    const entry = manifest.files[rel];
    if (current === null) {
      if (!createIfMissing) return actions.push({ action: "skip", path: rel, kind, reason: `${rel} does not exist; not created` });
      return actions.push({ action: "create", path: rel, kind, reason, content: `${markers[0]}\n${content}\n${markers[1]}\n`, hash: want, section: true });
    }
    const existing = extractSection(current, markers);
    if (existing === null) return actions.push({ action: "update", path: rel, kind, reason: `${reason} (append section)`, content: `${current.replace(/\n*$/, "\n")}\n${markers[0]}\n${content}\n${markers[1]}\n`, hash: want, section: true });
    const cur = sha(existing);
    if (cur === want) return actions.push({ action: "unchanged", path: rel, kind, reason, hash: want, section: true });
    if (entry && entry.hash === cur) return actions.push({ action: "update", path: rel, kind, reason, content: replaceSection(current, markers, content), hash: want, section: true });
    return actions.push({ action: "conflict", path: rel, kind, reason: "generated section was edited by a user", content: replaceSection(current, markers, content), hash: want, section: true });
  };

  // 1. Framework config
  fileAction(PROJECT_CONFIG_REL, buildFrameworkConfig(d, caps), "config", "enabled agents, aliases, specialists, validation commands");

  // 2. Project profile (versioned; regenerated only when the source hash changes)
  const profileRel = "project-context/project-profile.md";
  const profileCur = read(profileRel);
  if (profileCur === null) {
    actions.push({ action: "create", path: profileRel, kind: "profile", reason: "project profile", content: profileDocument(d, 1), hash: d.source_hash });
  } else {
    let fm = {};
    try { fm = parseFrontmatter(profileCur).data; } catch { /* treated as conflict below */ }
    const section = extractSection(profileCur, SECTION.profile);
    if (section === null) actions.push({ action: "conflict", path: profileRel, kind: "profile", reason: "profile exists without generated-section markers", content: profileDocument(d, 1), hash: d.source_hash });
    else if (fm.source_hash === d.source_hash) actions.push({ action: "unchanged", path: profileRel, kind: "profile", reason: "source hash unchanged", hash: d.source_hash });
    else {
      const version = (Number(fm.profile_version) || 0) + 1;
      const fresh = profileDocument(d, version);
      const rest = profileCur.slice(profileCur.indexOf(SECTION.profile[1]) + SECTION.profile[1].length);
      const head = fresh.slice(0, fresh.indexOf(SECTION.profile[1]) + SECTION.profile[1].length);
      actions.push({ action: "update", path: profileRel, kind: "profile", reason: `sources changed (profile v${version})`, content: head + rest, hash: d.source_hash });
    }
  }

  // 3. Specialists
  for (const s of caps.specialists) {
    const rel = `.claude/agents/${s.name}.md`;
    if (s.exists && !manifest.files[rel]) { actions.push({ action: "unchanged", path: rel, kind: "specialist", reason: "existing project agent with this name reused" }); continue; }
    fileAction(rel, buildSpecialist(s, d), "specialist", s.reason);
  }

  // 4. Gap tasks (deduplicated by origin across all statuses)
  const { tasks } = loadTasks(root);
  const origins = new Set(tasks.map((t) => t.data.origin).filter(Boolean));
  // Next id considers file names too, so unparseable task files are never collided with.
  let nextNum = Number(nextTaskId(root).slice(5));
  for (const g of caps.gaps) {
    const origin = `bootstrap:${g.id}`;
    const existingTask = tasks.find((t) => t.data.origin === origin);
    if (origins.has(origin)) { actions.push({ action: "unchanged", path: existingTask.relFile, kind: "task", reason: `gap ${g.id} already has a task (${existingTask.data.id}, ${existingTask.data.status})` }); continue; }
    const id = `TASK-${String(nextNum++).padStart(3, "0")}`;
    const slug = g.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 48);
    actions.push({ action: "create", path: `tasks/${id}-${slug}.md`, kind: "task", reason: `gap: ${g.id}`, content: gapTask(g, d, id), untracked: true });
  }

  // 5. README section (created if README missing) and CLAUDE.md pointer (only if CLAUDE.md exists)
  sectionAction("README.md", SECTION.readme, buildReadmeSection(d, caps), "readme", "usage instructions for the framework", { createIfMissing: true });
  sectionAction("CLAUDE.md", SECTION.claude, buildClaudeSection(), "claude", "short pointer to the framework", { createIfMissing: false });

  return { discovery: d, inventory: inv, capabilities: caps, actions, manifest_corrupt: Boolean(manifest.corrupt) };
}

// ---------------------------------------------------------------------- apply
export function apply(root, { force = false, discovery } = {}) {
  const p = plan(root, { discovery });
  const manifest = readManifest(root);
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  const written = [];
  for (const a of p.actions) {
    const abs = join(root, a.path);
    if (a.action === "create" || a.action === "update" || (a.action === "conflict" && force)) {
      if (a.action === "conflict") {
        const backup = join(root, ".claude/agent-framework/backup", `${a.path}.${stamp}`);
        mkdirSync(dirname(backup), { recursive: true });
        copyFileSync(abs, backup);
        a.backup = backup;
      }
      mkdirSync(dirname(abs), { recursive: true });
      writeFileSync(abs, a.content);
      if (!a.untracked) manifest.files[a.path] = { hash: a.hash, kind: a.kind, section: Boolean(a.section) };
      written.push(a.path);
      a.applied = true;
    } else if (a.action === "conflict") {
      const proposal = join(root, ".claude/agent-framework/proposed", a.path);
      mkdirSync(dirname(proposal), { recursive: true });
      writeFileSync(proposal, a.content);
      a.proposal = `.claude/agent-framework/proposed/${a.path}`;
    } else if (a.action === "unchanged" && a.hash && !manifest.files[a.path] && a.kind !== "task") {
      manifest.files[a.path] = { hash: a.hash, kind: a.kind, section: Boolean(a.section) };
    }
  }
  manifest.version = 1;
  manifest.generator = `${GENERATOR} ${pluginVersion()}`;
  const manifestText = JSON.stringify({ ...manifest, files: Object.fromEntries(Object.entries(manifest.files).sort()) }, null, 2) + "\n";
  const manifestPath = join(root, MANIFEST_REL);
  const oldManifest = existsSync(manifestPath) ? readFileSync(manifestPath, "utf8") : null;
  if (oldManifest !== manifestText) {
    mkdirSync(dirname(manifestPath), { recursive: true });
    writeFileSync(manifestPath, manifestText);
  }
  const report = renderReport(p, { mode: "apply", force });
  mkdirSync(join(root, "reports"), { recursive: true });
  writeFileSync(join(root, "reports", "bootstrap-report.md"), report);
  return { ...p, written };
}

