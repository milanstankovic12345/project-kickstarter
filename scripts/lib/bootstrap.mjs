export function validateProject(root) {
  const errors = [];
  const warnings = [];
  const registry = loadRegistry();
  const cfgPath = join(root, PROJECT_CONFIG_REL);
  if (!existsSync(cfgPath)) return { errors: [`${PROJECT_CONFIG_REL} missing — run bootstrap apply`], warnings };
  let cfg;
  try { cfg = readJson(cfgPath); } catch (e) { return { errors: [e.message], warnings }; }
  errors.push(...validateSchema(loadSchema("framework-config"), cfg).map((e) => `${PROJECT_CONFIG_REL} ${e}`));
  const localAgents = new Set(readAgents(join(root, ".claude", "agents")).map((a) => a.name).filter(Boolean));
  const specialistNames = new Set((cfg.specialists ?? []).map((s) => s.name));
  for (const a of cfg.enabled_agents ?? []) if (!registry.agents[a] && !localAgents.has(a) && !specialistNames.has(a)) errors.push(`enabled agent "${a}" does not exist`);
  for (const [fwName, local] of Object.entries(cfg.agent_aliases ?? {})) {
    if (!registry.agents[fwName]) errors.push(`alias source "${fwName}" is not a framework agent`);
    if (!localAgents.has(local)) errors.push(`alias target "${local}" not found in .claude/agents/`);
  }
  for (const s of cfg.specialists ?? []) {
    const f = join(root, ".claude", "agents", `${s.name}.md`);
    if (!existsSync(f)) { errors.push(`specialist ${s.name}: ${f} missing`); continue; }
    try {
      const { data } = parseFrontmatter(readFileSync(f, "utf8"));
      if (data.name !== s.name) errors.push(`specialist ${s.name}: frontmatter name is "${data.name}"`);
      if (data.model && !isAllowedModel(data.model)) errors.push(`specialist ${s.name}: model "${data.model}" not allowed`);
    } catch (e) { errors.push(`specialist ${s.name}: ${e.message}`); }
  }
  for (const [k, v] of Object.entries(cfg.routing?.tiers ?? {})) if (v.model && !isAllowedModel(v.model)) errors.push(`routing override tier ${k}: model "${v.model}" not allowed`);
  const manifest = readManifest(root);
  if (manifest.corrupt) errors.push(`${MANIFEST_REL} is not valid JSON`);
  for (const rel of Object.keys(manifest.files)) if (!existsSync(join(root, rel))) warnings.push(`managed file ${rel} was deleted`);
  const profile = join(root, "project-context/project-profile.md");
  if (!existsSync(profile)) errors.push("project-context/project-profile.md missing");
  else {
    try {
      const { data } = parseFrontmatter(readFileSync(profile, "utf8"));
      const current = discover(root).source_hash;
      if (!data.source_hash) warnings.push("project profile has no source_hash (not generated by bootstrap) — run bootstrap apply to regenerate");
      else if (data.source_hash !== current) warnings.push(`project profile is stale (profile ${data.source_hash}, sources ${current}) — run bootstrap apply`);
    } catch (e) { errors.push(`project profile: ${e.message}`); }
  }
  for (const m of discover(root).manifests_invalid ?? []) errors.push(`manifest ${m} is not valid JSON; discovery could not read its dependencies`);
  const t = validateTaskSet(root, { config: loadConfig(root) });
  errors.push(...t.errors.map((e) => `task ${e.task ?? e.file}: ${e.message}`));
  warnings.push(...t.warnings.map((w) => `task ${w.task ?? w.file}: ${w.message}`));
  return { errors, warnings };
}

// --------------------------------------------------------------------- report
export function renderReport(p, { mode, force = false } = {}) {
  const by = (act) => p.actions.filter((a) => a.action === act);
  const line = (a) => `- \`${a.path}\` — ${a.reason}${a.proposal ? ` → proposal at \`${a.proposal}\`` : ""}${a.backup ? " (backup kept)" : ""}`;
  const d = p.discovery;
  return [
    `# Bootstrap report`,
    "",
    `Mode: ${mode}${force ? " (--force)" : ""} · Generator: ${GENERATOR} ${pluginVersion()} · Source hash: ${d.source_hash}`,
    "",
    "## Discovery",
    "",
    `Languages: ${d.languages.map((l) => l.name).join(", ") || "none"} · Frameworks: ${d.frameworks.map((f) => f.name).join(", ") || "none"} · Tests: ${d.testing.test_files} files · CI: ${d.ci.map((c) => c.system).join(", ") || "none"} · UI: ${d.ui.has_ui ? "yes" : "no"}`,
    "",
    ...(d.manifests_invalid?.length ? [`**Unreadable manifests (fix first):** ${d.manifests_invalid.map((m) => `\`${m}\``).join(", ")}`, ""] : []),
    "## Agents",
    "",
    "Enabled:",
    ...p.capabilities.enabled.map((a) => `- \`${a.name}\` — ${a.reason}`),
    "",
    "Omitted (no project signal):",
    p.capabilities.omitted.length ? p.capabilities.omitted.map((a) => `\`${a.name}\``).join(", ") : "none",
    "",
    "Reused existing components:",
    p.capabilities.reused.length ? p.capabilities.reused.map((r) => `- ${r.kind} \`${r.name}\` — ${r.note}`).join("\n") : "- none",
    "",
    "Project specialists:",
    p.capabilities.specialists.length ? p.capabilities.specialists.map((s) => `- \`${s.name}\` (${s.tier}) — ${s.reason}${s.exists ? " (already existed)" : ""}`).join("\n") : "- none justified",
    "",
    "## File actions",
    "",
    `Created (${by("create").length}):`, ...by("create").map(line), "",
    `Updated (${by("update").length}):`, ...by("update").map(line), "",
    `Unchanged (${by("unchanged").length}):`, ...by("unchanged").map(line), "",
    `Conflicts (${by("conflict").length}) — not overwritten${force ? " unless --force" : ""}:`, ...by("conflict").map(line), "",
    `Skipped (${by("skip").length}):`, ...by("skip").map(line), "",
    "## Next steps",
    "",
    "1. Review generated tasks in `tasks/` (status `draft`) and promote: `node <plugin-root>/scripts/tasks.mjs transition TASK-NNN ready`.",
    "2. Enrich `project-context/project-profile.md` Notes (project-discoverer agent) if needed.",
    "3. Run `/project-kickstarter:run-task` to execute ready tasks.",
    by("conflict").length ? "4. Resolve conflicts: diff each proposal against your file and merge manually, or re-run apply with `--force` (backups are kept)." : "",
  ].filter((x) => x !== undefined).join("\n") + "\n";
}
