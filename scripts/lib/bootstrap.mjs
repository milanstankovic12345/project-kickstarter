export function sha(text) {
  return createHash("sha256").update(String(text).replace(/\r\n?/g, "\n")).digest("hex").slice(0, 16);
}

function pluginVersion() {
  try { return readJson(pluginFile(".claude-plugin", "plugin.json")).version ?? "0.0.0"; } catch { return "0.0.0"; }
}

// ---------------------------------------------------------------- conditions
function getPath(obj, path) {
  let cur = obj;
  for (const key of path.split(".")) {
    cur = Array.isArray(cur) ? cur.map((x) => x?.[key]).flat() : cur?.[key];
  }
  return cur;
}

function isEmpty(v) {
  if (v == null || v === false || v === "") return true;
  if (Array.isArray(v)) return v.length === 0;
  if (typeof v === "object") return Object.keys(v).length === 0;
  return false;
}

export function evaluate(cond, d) {
  if (cond.any) return cond.any.some((c) => evaluate(c, d));
  if (cond.all) return cond.all.every((c) => evaluate(c, d));
  return Object.entries(cond).every(([path, expected]) => {
    const v = getPath(d, path);
    if (expected === "nonempty") return !isEmpty(v);
    if (expected === "empty") return isEmpty(v);
    if (Array.isArray(expected)) return (Array.isArray(v) ? v : [v]).some((x) => expected.includes(x));
    if (expected && typeof expected === "object" && "gte" in expected) return Number(v) >= expected.gte;
    return v === expected;
  });
}

// ------------------------------------------------------------------- planning
export function inventory(root) {
  const agents = readAgents(join(root, ".claude", "agents"));
  const skills = readSkills(join(root, ".claude", "skills"));
  let settingsHooks = [];
  for (const f of [".claude/settings.json", ".claude/settings.local.json"]) {
    const p = join(root, f);
    if (!existsSync(p)) continue;
    try { settingsHooks.push(...Object.keys(readJson(p).hooks ?? {}).map((e) => `${f}:${e}`)); } catch { settingsHooks.push(`${f}:INVALID_JSON`); }
  }
  return {
    agents: agents.map((a) => ({ name: a.name, file: a.file, error: a.error ?? null, managed: /Generated by project-kickstarter bootstrap/.test(a.body) })),
    skills: skills.map((s) => ({ name: s.name, folder: s.folder, error: s.error ?? null })),
    settings_hooks: settingsHooks,
    framework_config: existsSync(join(root, PROJECT_CONFIG_REL)),
  };
}

export function mapCapabilities(d, inv) {
  const registry = loadRegistry();
  const cmap = readJson(pluginFile("config", "capability-map.json"));
  const enabled = new Map();
  for (const [name, a] of Object.entries(registry.agents)) if (a.always) enabled.set(name, "core agent (always enabled)");
  for (const rule of cmap.agent_rules) {
    if (!evaluate(rule.when, d)) continue;
    for (const name of rule.enable) if (!enabled.has(name)) enabled.set(name, `${rule.reason} [rule ${rule.id}]`);
  }
  const omitted = Object.keys(registry.agents).filter((n) => !enabled.has(n)).map((name) => ({ name, reason: "no matching project signal" }));

  // Reuse: existing project agents override or alias framework agents.
  const reused = [];
  const aliases = {};
  const existing = new Set(inv.agents.filter((a) => a.name && !a.managed).map((a) => a.name));
  for (const name of existing) {
    if (registry.agents[name]) reused.push({ kind: "agent", name, covers: name, note: "project agent with the same name overrides the framework agent" });
    else if (cmap.equivalents[name]) {
      aliases[cmap.equivalents[name]] = name;
      reused.push({ kind: "agent", name, covers: cmap.equivalents[name], note: `existing ${name} used for ${cmap.equivalents[name]} tasks` });
      if (!enabled.has(cmap.equivalents[name])) enabled.set(cmap.equivalents[name], `covered by existing project agent ${name}`);
    } else reused.push({ kind: "agent", name, covers: null, note: "existing project agent kept; assignable in tasks" });
  }
  for (const s of inv.skills) if (s.name) reused.push({ kind: "skill", name: s.name, covers: null, note: "existing project skill kept" });

  const specialists = [];
  for (const rule of cmap.specialist_rules) {
    if (!evaluate(rule.when, d)) continue;
    const already = existing.has(rule.name) || inv.agents.some((a) => a.name === rule.name);
    specialists.push({ name: rule.name, tier: rule.tier, access: rule.access, focus: rule.focus, reason: rule.reason, exists: already });
  }
  const gaps = cmap.gap_rules.filter((g) => evaluate(g.when, d));
  return {
    enabled: [...enabled].map(([name, reason]) => ({ name, reason })).sort((a, b) => a.name.localeCompare(b.name)),
    omitted,
    reused,
    aliases,
    specialists,
    gaps,
  };
}

// --------------------------------------------------------- content builders
function validationCommands(d) {
  const out = {};
  for (const k of ["install", "build", "test", "lint", "typecheck", "check", "e2e"]) if (d.commands[k]) out[k] = d.commands[k].cmd;
  return out;
}

export function buildFrameworkConfig(d, caps) {
  return JSON.stringify({
    version: 1,
    generated_by: `${GENERATOR} ${pluginVersion()}`,
    enabled_agents: caps.enabled.map((a) => a.name),
    agent_aliases: caps.aliases,
    specialists: caps.specialists.map((s) => ({ name: s.name, tier: s.tier })),
    validation_commands: validationCommands(d),
    concurrency: { max_parallel: 3 },
    gates: { required_reviews: ["code"] },
  }, null, 2) + "\n";
}

function bullet(items, empty = "_none detected_") {
  return items.length ? items.map((x) => `- ${x}`).join("\n") : empty;
}

